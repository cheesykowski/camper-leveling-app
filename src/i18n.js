export function normalizeLanguage(value) {
  return value === 'de' ? 'de' : 'en';
}

export function translate(language, message, values = {}) {
  let text = message;
  if (language === 'de') {
    if (!Object.prototype.hasOwnProperty.call(german, message)) {
      throw new Error(`Missing German translation: ${message}`);
    }
    text = german[message];
  }
  return text.replace(/\{(\w+)\}/g, (placeholder, key) => {
    if (!Object.prototype.hasOwnProperty.call(values, key)) {
      throw new Error(`Missing translation value: ${key}`);
    }
    return String(values[key]);
  });
}
